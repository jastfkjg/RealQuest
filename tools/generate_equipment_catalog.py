"""Generate the client presentation catalogue from the authoritative server catalogue."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'backend/app/equipment_catalog.json').read_text())
ids=[r['id'] for r in data['equipment']]
assert len(ids)==len(set(ids)) and all(r['route'] in ['martial','science','magic'] for r in data['equipment'])
text='// Generated by tools/generate_equipment_catalog.py; edit backend/app/equipment_catalog.json.\n'
text+='export const gearCatalog = '+json.dumps({r['id']:r for r in data['equipment']},ensure_ascii=False,separators=(',',':'))+' as const;\n'
text+='export const gearMaterials = '+json.dumps(data['materials'],ensure_ascii=False,separators=(',',':'))+' as const;\n'
text+="export const routeNames:Record<string,string>={martial:'基础冷兵器',science:'科学武器',magic:'魔法武器',gear:'护具与饰品'};\nexport const slotNames:Record<string,string>={weapon:'主手武器',body:'护衣',feet:'鞋靴',charm:'饰品'};\n"
p=root/'shared/game/gearCatalog.ts'
if not p.exists() or p.read_text()!=text:p.write_text(text)
