"""Generate Cocos/shared ranch presentation data from the server catalogue."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'backend/app/ranch_catalog.json').read_text())
assert len(data['animals'])==7 and len({a['id'] for a in data['animals']})==7
text='// Generated by tools/generate_ranch_catalog.py; edit backend/app/ranch_catalog.json.\n'
text+='export const ranchCatalog = '+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n'
p=root/'shared/game/ranchCatalog.ts'
if not p.exists() or p.read_text()!=text:p.write_text(text)
