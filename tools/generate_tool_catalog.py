"""Generate typed client rules from the authoritative tool catalogue."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
data = json.loads((root/'backend/app/tool_catalog.json').read_text())
text = '// Generated by tools/generate_tool_catalog.py; edit backend/app/tool_catalog.json.\n'
text += 'export const toolCatalog = ' + json.dumps(data, ensure_ascii=False, indent=2) + ' as const;\n'
(root/'shared/game/toolCatalog.ts').write_text(text)
