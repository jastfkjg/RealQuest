"""Regenerate client catalogue from server source of truth."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'backend/app/crops.json').read_text())
text = '// Generated by tools/generate_crop_catalog.py; edit backend/app/crops.json.\n'
text += 'export interface CropDefinition {id:string;name:string;seed:string;item:string;level:number;buy:number;sell:number;days:number;yield:number;harvests:number;regrow_days:number;note:string}\n'
text += 'export const crops:CropDefinition[] = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
(root / 'shared/game/cropCatalog.ts').write_text(text)
